//! The browser client: the pages that start it (for a signed-in visitor) and the files it loads (`forge-web` serves them).
//!
//! Every screen is one of these paths (the address keeps `?repo=`, `?tag=`, `?storage=` and `?path=` for the client to read),
//! so the links of the old pages keep working.

use crate::routers::ui::common::ActorOrRedirect;
use forge_web::Client;
use quench_http::prelude::*;

static CLIENT: Client = Client::new("Warehouse", warehouse_web::stylesheet)
    .framed()
    .icon(include_bytes!("../../../../../icon.png"));

/// The page, or the way to sign in.
fn page(who: ActorOrRedirect) -> Response {
    match who.or_redirect() {
        Ok(_) => CLIENT.page(),
        Err(redirect) => redirect,
    }
}

// The screens of the client, each with and without the trailing slash. Spelled out (not generated by a macro) so
// that the security census, which reads the route attributes, sees every one of them.
#[get("/ui/home")]
pub(super) async fn home(who: ActorOrRedirect) -> Response {
    page(who)
}

